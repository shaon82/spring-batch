package com.leads.spring_batch.batch.mapper;

import static org.assertj.core.api.Assertions.assertThat;

import com.leads.spring_batch.destination.LoanAccInfo;
import com.leads.spring_batch.source.LoanAccInfoStage;
import org.junit.jupiter.api.Test;

class LoanAccInfoMapperTest {

  private final LoanAccInfoMapper mapper = new LoanAccInfoMapper();

  @Test
  void copiesEveryBusinessFieldButNotTheId() {
    LoanAccInfoStage source =
        new LoanAccInfoStage()
            .setId(42L)
            .setAccountNumber("ACC-1")
            .setAccountName("Rahim")
            .setAccountType("PERSONAL")
            .setAmount(1000.0)
            .setInterestRate(9.5)
            .setInterest(95.0)
            .setPayment(250.0)
            .setStatus(false);

    LoanAccInfo target = mapper.toDestination(source);

    assertThat(target.getId()).isNull(); // generated by the destination table
    assertThat(target.getAccountNumber()).isEqualTo("ACC-1");
    assertThat(target.getAccountName()).isEqualTo("Rahim");
    assertThat(target.getAccountType()).isEqualTo("PERSONAL");
    assertThat(target.getAmount()).isEqualTo(1000.0);
    assertThat(target.getInterestRate()).isEqualTo(9.5);
    assertThat(target.getInterest()).isEqualTo(95.0);
    assertThat(target.getPayment()).isEqualTo(250.0);
    assertThat(target.getStatus()).isFalse();
  }

  @Test
  void keepsNullsAsNulls() {
    LoanAccInfo target = mapper.toDestination(new LoanAccInfoStage());

    assertThat(target.getAccountNumber()).isNull();
    assertThat(target.getAmount()).isNull();
    assertThat(target.getStatus()).isNull();
  }
}
